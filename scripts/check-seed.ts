export {};
process.env.PGLITE_MEMORY = "1";
const { getDb, schema } = await import("@/lib/db");
const t = Date.now();
const db = await getDb();
console.log("seeded in", Date.now() - t, "ms");
const ds = await db.select().from(schema.dossiers);
for (const d of ds) console.log(d.reference, d.status, d.service, d.data.property.straat, "akteL", d.data.akteLevering?.version, d.data.akteLevering?.status, "akteH", d.data.akteHypotheek?.version, "kad", d.data.kadaster.status);
const { loadDossierView } = await import("@/lib/domain/dossier");
const { koperSteps, verkoperSteps, notaryChecks } = await import("@/lib/workflow/steps");
const main = ds.find((d) => d.reference === "AK-2026-4821")!;
const v = (await loadDossierView(main.id))!;
for (const s of koperSteps(v)) console.log(" K", s.nr, s.title, "|", s.state, "|", s.label);
for (const s of verkoperSteps(v)) console.log(" V", s.nr, s.title, "|", s.state, "|", s.label);
for (const c of notaryChecks(v)) console.log(" N", c.nr, c.title, "|", c.ready, c.status, c.readyLabel, c.flags.length);
console.log("docs", v.documents.map((d) => d.kind).join(", "));
console.log("handovers", v.handovers.map((h) => h.reason));
console.log("payoffs", v.payoffs.map((p) => [p.lender, p.status, p.amount]));
console.log("nota koper", v.data.notaKoper?.saldo, "verkoper", v.data.notaVerkoper?.saldo);
const evs = await db.select().from(schema.events);
console.log("events", evs.length, "errors", evs.filter((e) => e.type === "automation.error").map((e) => e.message));
const ms = await db.select().from(schema.emails);
console.log("emails", ms.length, ms.map((m) => m.template).join(","));
process.exit(0);
